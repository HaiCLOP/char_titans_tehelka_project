import type { ALLOWED_IMAGE_TYPES } from "@/lib/domain";

/** Checks an upload's magic bytes so a renamed non-image is rejected even if the browser lies about its type. */
export function sniffImage(b: Uint8Array): (typeof ALLOWED_IMAGE_TYPES)[number] | null {
  if (b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return "image/jpeg";
  if (b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47) return "image/png";
  const ascii = (from: number, to: number) => String.fromCharCode(...b.subarray(from, to));
  if (ascii(0, 4) === "RIFF" && ascii(8, 12) === "WEBP") return "image/webp";
  return null;
}
